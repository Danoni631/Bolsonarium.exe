void StartAllThreads()
{
    int AllStages = sizeof(ThreadList) / sizeof(ThreadList[0]);

    while (StartEffects)
    {
        int RandomThread = rand() % AllStages;

        ThreadList[RandomThread]();
    }

    InvalidateRect(0, 0, 1);
}

void StopGDIThreads()
{
    StartEffects = false;
}

